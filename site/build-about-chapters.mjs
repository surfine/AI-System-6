#!/usr/bin/env node

// Build About's four generated chapters from the official site, so the site
// stays the one source for these words (decision D7, 2026-10-16).
//
// Mark a paragraph in site/index.html with data-desk-chapter="desk|eras|
// afterHours|model"; a mark on an item may add data-desk-open="<command id>",
// which becomes a real "Open" button on the desk. Wrap a sentence that is only
// true of the page (a screenshot caption, "scroll down") in
// <span data-desk-skip>…</span>. node site/build-zh-page.mjs carries the marks
// to the Chinese page; this script reads both pages and writes
// apps/desktop/app/content/about-chapters.js. tooling/verify-site.mjs re-runs
// it and fails on a stale file, an unknown command, or an emptied chapter.
//
//   node site/build-about-chapters.mjs          write the content file
//   node site/build-about-chapters.mjs --check  exit 1 when stale

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseHTML } from "linkedom";

const siteRoot = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(siteRoot, "..");
export const aboutChapterIds = ["desk", "eras", "afterHours", "model"];
export const aboutChaptersOutput = join(repoRoot, "apps/desktop/app/content/about-chapters.js");

const cjk = /[　-鿿＀-￯]/;

// Text as a reader sees it: line breaks become a space between Latin words
// and nothing between Chinese ones, skipped spans are dropped.
function readable(node) {
  const clone = node.cloneNode(true);
  clone.querySelectorAll("[data-desk-skip], img, svg, .tour-num, .way-num, .way-illo, script").forEach((child) => child.remove());
  clone.querySelectorAll("br").forEach((br) => br.replaceWith("\n"));
  return String(clone.textContent || "")
    .split("\n")
    .map((part) => part.replace(/\s+/g, " ").trim())
    .filter(Boolean)
    .reduce((text, part) => {
      if (!text) return part;
      const joinTight = cjk.test(text.slice(-1)) && cjk.test(part[0]);
      return `${text}${joinTight ? "" : " "}${part}`;
    }, "");
}

function blockFrom(node) {
  const open = node.getAttribute("data-desk-open") || "";
  const tag = node.tagName.toLowerCase();
  if (/^h[1-6]$/.test(tag)) {
    return open ? { kind: "item", title: readable(node), body: "", open } : { kind: "head", text: readable(node) };
  }
  if (tag === "p") return { kind: "lead", text: readable(node) };
  const titleNode = node.querySelector("h2, h3, summary, .proof-label");
  const title = titleNode ? readable(titleNode) : "";
  const bodyNodes = [...node.querySelectorAll(".proof-line, p")]
    .filter((child) => !child.closest("summary") && !child.matches(".tour-num, .way-num"));
  const body = bodyNodes.map(readable).filter(Boolean).join(" ");
  const block = { kind: "item", title, body };
  if (open) block.open = open;
  return block;
}

export function chaptersFromHtml(html) {
  const { document } = parseHTML(html);
  const chapters = Object.fromEntries(aboutChapterIds.map((id) => [id, []]));
  document.querySelectorAll("[data-desk-chapter]").forEach((node) => {
    const id = node.getAttribute("data-desk-chapter");
    if (!chapters[id]) throw new Error(`unknown data-desk-chapter="${id}"`);
    const block = blockFrom(node);
    if ((block.text || block.title || "").trim()) chapters[id].push(block);
  });
  return chapters;
}

export function renderAboutChapters() {
  const en = chaptersFromHtml(readFileSync(join(siteRoot, "index.html"), "utf8"));
  const zh = chaptersFromHtml(readFileSync(join(siteRoot, "zh-CN.html"), "utf8"));
  const chapters = Object.fromEntries(aboutChapterIds.map((id) => [id, { en: en[id], zh: zh[id] }]));
  return `// Generated by site/build-about-chapters.mjs from site/index.html and site/zh-CN.html. Do not edit.\nwindow.AISystem6AboutChapters = Object.freeze(${JSON.stringify({ source: "site/index.html", chapters }, null, 2)});\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = renderAboutChapters();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(aboutChaptersOutput, "utf8"); } catch {}
    if (current !== next) {
      console.error("FAIL apps/desktop/app/content/about-chapters.js is stale; run node site/build-about-chapters.mjs");
      process.exit(1);
    }
    console.log("OK  About chapters match the official site");
  } else {
    writeFileSync(aboutChaptersOutput, next);
    console.log("wrote apps/desktop/app/content/about-chapters.js");
  }
}
