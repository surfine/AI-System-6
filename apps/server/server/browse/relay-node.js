// The browse origin, served by the same Node process as the desk.
//
// Time Machine's web engine shows a proxied page in an iframe whose origin is
// not the desk's: the desk keeps the writer's projects in IndexedDB, and a
// page from the open web must never share an origin with that. This module
// answers every request whose Host is the browse host, and nothing else
// answers them: the desk's API routes and static files are not reachable
// here, and nothing here is reachable from the desk's host.
//
//   /__ais6/sw.js, /__ais6/shim.js ...  the engine's own files (apps/browse)
//   /__ais6/relay                        one request out to the web
//   /__ais6/relay-ws                     one WebSocket out to the web
//   anything else                        the bootstrap page, which installs
//                                        the service worker and reloads
//
// The relay's rules (who may use it, which headers and cookies cross) live in
// core.mjs, shared with the Pages Functions copy. What lives here is only how
// Node moves bytes: DNS-pinned sockets, streaming both ways, byte caps.

