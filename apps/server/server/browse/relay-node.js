// --- Configuration ---------------------------------------------------------

/** @type {{ origin: string, host: string, secret: string, available: boolean, reason: string } | null} */
let cachedConfig = null;

/**
 * Where the browse origin lives. A Mac uses browse.localhost: browsers send
 * *.localhost to the loopback interface and treat it as a secure context, so
 * the service worker may register there, and it is a different origin from
 * both localhost and 127.0.0.1, where the desk may be open.
 *
 * @param {number} [port]
 */
function browseConfig(port = Number(process.env.PORT || 4173)) {
  if (cachedConfig) return cachedConfig;
  const configured = String(process.env.AI_SYSTEM6_BROWSE_ORIGIN || "").trim();
  let origin = configured || (isPublicDeployment ? "" : `http://browse.localhost:${port}`);
  let reason = "";
  try {
    const parsed = new URL(origin);
    if (parsed.pathname !== "/" || parsed.search || parsed.hash || parsed.username || parsed.password) {
      throw new Error("bad");
    }
    origin = parsed.origin;
  } catch {
    origin = "";
    reason = isPublicDeployment ? "browse_origin_not_configured" : "browse_origin_invalid";
  }
  let secret = String(process.env.AI_SYSTEM6_BROWSE_SECRET || "");
  if (secret.length < 24) {
    if (isPublicDeployment) {
      secret = "";
      reason ||= "browse_secret_not_configured";
    } else {
      // A Mac's relay lives as long as its server; tokens and sealed jars from
      // an earlier run are meant to stop opening when it restarts.
      secret = crypto.randomBytes(32).toString("base64url");
    }
  }
  cachedConfig = {
    origin,
    host: origin ? new URL(origin).host.toLowerCase() : "",
    secret,
    available: !!origin && !!secret,
    reason,
  };
  return cachedConfig;
}

/** @param {import("node:http").IncomingMessage} req */
function isBrowseHostRequest(req) {
  const config = browseConfig();
  if (!config.available) return false;
  return String(req.headers.host || "").toLowerCase() === config.host;
}

/** @param {import("node:http").IncomingMessage} req */
async function browseClientBinding(req) {
  if (!isPublicDeployment) return "";
  return core.browseClientDigest(clientIp(req), String(req.headers["user-agent"] || ""));
}

// --- Token route (desk host) ------------------------------------------------

/**
 * POST /api/browse/token. Runs behind the desk's own guard: Turnstile session
 * on the public site, the loopback origin check on a Mac.
 *
 * @param {import("node:http").IncomingMessage} req
 * @param {import("node:http").ServerResponse} res
 */
async function handleBrowseToken(req, res) {
  const config = browseConfig();
  res.setHeader("Cache-Control", "no-store");
  if (!config.available) {
    res.writeHead(503, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ error: "The web engine is not set up on this server.", code: config.reason }));
    return;
  }
  const body = await readSmallJson(req);
  const minted = await core.mintBrowseToken(config.secret, {
    sid: typeof body?.sid === "string" ? body.sid : undefined,
    client: await browseClientBinding(req),
  });
  res.writeHead(200, { "Content-Type": "application/json" });
  res.end(JSON.stringify({ ...minted, origin: config.origin }));
}

/** @param {import("node:http").IncomingMessage} req */
function readSmallJson(req) {
  return new Promise((resolve) => {
    let size = 0;
    /** @type {Buffer[]} */
    const chunks = [];
    req.on("data", (chunk) => {
      size += chunk.length;
      if (size > 4096) {
        req.destroy();
        resolve(null);
        return;
      }
      chunks.push(chunk);
    });
    req.on("end", () => {
      try {
        resolve(chunks.length ? JSON.parse(Buffer.concat(chunks).toString("utf8")) : {});
      } catch {
        resolve({});
      }
    });
    req.on("error", () => resolve(null));
  });
}

