#!/usr/bin/env node
// Writes apps/desktop/app/content/release-notes.js: this version's curated
// notes, at most eight per language, for About's "Release Notes" list.
//
// Source: internal/operations/RELEASE-NOTES.md (the canonical text the GitHub
// release publishes) and its zh-CN mirror. internal/ never ships, so the
// desk carries this generated copy instead; tests/features/release-notes-desk
// fails when the copy is stale.
//
//   node tooling/build-release-notes-content.mjs          write the file
//   node tooling/build-release-notes-content.mjs --check  exit 1 when stale

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const releaseNotesLimit = 8;
export const releaseNotesOutput = path.join(root, "apps/desktop/app/content/release-notes.js");

// The bullets of one "## vX.Y.Z" section. A bullet may wrap onto indented
// continuation lines; emphasis markers are dropped because the desk shows
// plain text.
export function sectionBullets(markdown, version) {
  const lines = String(markdown).split("\n");
  const start = lines.findIndex((line) => line.trim() === `## v${version}`);
  if (start < 0) return [];
  const bullets = [];
  for (const line of lines.slice(start + 1)) {
    if (/^##\s/.test(line)) break;
    if (/^- /.test(line)) bullets.push(line.slice(2).trim());
    else if (/^\s+\S/.test(line) && bullets.length) bullets[bullets.length - 1] += ` ${line.trim()}`;
  }
  return bullets.map((bullet) => bullet.replace(/\*\*/g, "").replace(/`/g, "").trim()).filter(Boolean);
}

export async function renderReleaseNotesContent() {
  const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  const en = sectionBullets(await readFile(path.join(root, "internal/operations/RELEASE-NOTES.md"), "utf8"), pkg.version);
  const zh = sectionBullets(await readFile(path.join(root, "internal/operations/RELEASE-NOTES.zh-CN.md"), "utf8"), pkg.version);
  const payload = {
    version: pkg.version,
    en: en.slice(0, releaseNotesLimit),
    zh: (zh.length ? zh : en).slice(0, releaseNotesLimit),
  };
  return `// Generated by tooling/build-release-notes-content.mjs from internal/operations/RELEASE-NOTES*.md. Do not edit.\nwindow.AISystem6ReleaseNotes = Object.freeze(${JSON.stringify(payload, null, 2)});\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const next = await renderReleaseNotesContent();
  if (process.argv.includes("--check")) {
    const current = await readFile(releaseNotesOutput, "utf8").catch(() => "");
    if (current !== next) {
      console.error("FAIL apps/desktop/app/content/release-notes.js is stale; run node tooling/build-release-notes-content.mjs");
      process.exit(1);
    }
    console.log("OK  release notes content is current");
  } else {
    await writeFile(releaseNotesOutput, next);
    console.log(`wrote ${path.relative(root, releaseNotesOutput)}`);
  }
}
