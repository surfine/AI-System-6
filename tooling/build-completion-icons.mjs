import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { COMPLETION_NEW_IDS, COMPLETION_EXTENDED_IDS, COMPLETION_ERAS } from './lib/completion-icon-inventory.mjs';
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const themes=join(root,'apps/desktop/assets/themes');
const sourceRoot='tooling/icon-generation/completion';
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
// Source art is generated by built-in Image Gen. This build only fits that
// artwork to native tiers, preserves alpha and quantises the 1-bit family.
async function fitSource(source,size) {
  const image=sharp(source);
  const opaqueTile=existsSync(source.replace('/masters/','/prompts/').replace(/\.png$/,'-opaque.txt'));
  if(!(await image.metadata()).hasAlpha&&!opaqueTile) throw new Error(`Source has no alpha: ${source}`);
  const margin=Math.max(1,Math.round(size/32));
  return (opaqueTile?image:image.trim({threshold:10})).resize(size-2*margin,size-2*margin,{fit:'contain',background:'#00000000',kernel:sharp.kernel.lanczos3})
    .extend({top:margin,bottom:margin,left:margin,right:margin,background:'#00000000'})
    .toColourspace('srgb').ensureAlpha().raw().toBuffer({resolveWithObject:true});
}
function classicPixels(data,size,mask=false) {
  function runs(kind) {
    let result='';
    for(let y=0;y<size;y++) {
      let start=-1;
      for(let x=0;x<=size;x++) {
        const i=(y*size+x)*4;
        const lum=data[i]*.2126+data[i+1]*.7152+data[i+2]*.0722;
        // The compact tier retains more ink rather than turning narrow seams
        // into gray antialiasing. Geometry stays the generated object's own.
        const on=x<size&&data[i+3]>=128&&(kind==='mask'||lum<(size===16?184:160));
        if(on&&start<0) start=x;
        if(!on&&start>=0){result+=`M${start} ${y}h${x-start}v1H${start}Z`;start=-1;}
      }
    }
    return result;
  }
  const silhouette=runs('mask');
  const paths=mask?`<path d="${silhouette}" fill="#000"/>`:`<path d="${silhouette}" fill="#fff"/><path d="${runs('ink')}" fill="#000"/>`;
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">${paths}</svg>\n`);
}
export async function buildCompletionIcons({eras=COMPLETION_ERAS,partial=false}={}) {
  const ledgerPath=join(themes,'completion-icon-extension.json');
  const ledger=existsSync(ledgerPath)?JSON.parse(readFileSync(ledgerPath)):{eras:{}};
  Object.assign(ledger,{schemaVersion:2,generatedBy:'tooling/build-completion-icons.mjs',source:'tooling/lib/completion-icon-inventory.mjs',engine:'built-in Image Gen',modelVersion:'not exposed by tool',nativeReplica:false,referenceValidated:false,sourceKind:'original-generated-era-illustration',historicalReviewStatus:'original-adaptation-not-a-historical-replica',sizePolicy:'Native-size derivatives of individual generated masters; 1-bit optical threshold at 16/32, transparent fitted raster tiers elsewhere.'});
  ledger.sourceSha256=sha(readFileSync(join(root,ledger.source)));
  let count=0;
  for(const era of eras) {
    if(!COMPLETION_ERAS.includes(era)) continue;
    const ids=[...COMPLETION_NEW_IDS,...(['big-sur','nextstep'].includes(era)?COMPLETION_EXTENDED_IDS:[])];
    const sizes=era==='classic'?[16,32]:era==='platinum'?[16,32,42,64,128]:era==='snow-leopard'?[16,32,64,128,512]:[16,32,64,128];
    const variants=era==='liquid-glass'?['default','dark','clear']:['default'];
    mkdirSync(join(themes,era,'icons'),{recursive:true});
    const icons={};
    for(const id of ids) {
      const sources=Object.fromEntries(variants.map(variant=>[variant,`${sourceRoot}/masters/${era}/${id}${variant==='default'?'':`-${variant}`}.png`]));
      if(Object.values(sources).some(p=>!existsSync(join(root,p)))) {
        if(partial)continue;
        throw new Error(`Missing Image Gen master for ${era}/${id}; no code-art fallback is allowed`);
      }
      const entry={sourceKind:'original-generated-era-illustration',sources:Object.fromEntries(Object.entries(sources).map(([variant,file])=>[variant,{file,sha256:sha(readFileSync(join(root,file))),prompt:(()=>{const base=`${sourceRoot}/prompts/${era}/${id}${variant==='default'?'':`-${variant}`}`;return existsSync(join(root,base+'-repair.txt'))?base+'-repair.txt':existsSync(join(root,base+'-opaque.txt'))?base+'-opaque.txt':existsSync(join(root,base+'-final.txt'))?base+'-final.txt':base+'.txt';})()}])),sizes:{},assets:{},...(era==='liquid-glass'?{appearanceSizes:{}}:{})};
      for(const size of sizes) for(const appearance of variants) {
        const {data,info}=await fitSource(join(root,sources[appearance]),size);
        const file=`icons/${id}-${size}${era==='liquid-glass'?`-${appearance}`:''}.${era==='classic'?'svg':'png'}`;
        const bytes=era==='classic'?classicPixels(data,size):await sharp(data,{raw:info}).withIccProfile('srgb').png({compressionLevel:9}).toBuffer();
        writeFileSync(join(themes,era,file),bytes);count++;
        entry.assets[file]={sha256:sha(bytes),width:size,height:size};
        if(appearance==='default') entry.sizes[size]=file;
        if(era==='liquid-glass') entry.appearanceSizes[`${size}-${appearance}`]=file;
        if(era==='classic') {
          const maskFile=`icons/${id}-mask-${size}.svg`,mask=classicPixels(data,size,true);
          writeFileSync(join(themes,era,maskFile),mask);count++;
          entry.assets[maskFile]={sha256:sha(mask),width:size,height:size};
        }
      }
      icons[id]=entry;
    }
    ledger.eras[era]={icons};
  }
  ledger.complete=COMPLETION_ERAS.every(era=>Object.keys(ledger.eras[era]?.icons||{}).length===(['big-sur','nextstep'].includes(era)?9:3));
  writeFileSync(ledgerPath,JSON.stringify(ledger,null,2)+'\n');
  console.log(`Image Gen completion: ${count} assets rebuilt; complete=${ledger.complete}`);
  return ledger;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) await buildCompletionIcons({partial:process.argv.includes('--partial')});
