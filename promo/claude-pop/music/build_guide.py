class Band:
    def __init__(self, S, events, dur):
        self.S, self.E, self.dur = S, events, dur
        self.spb = 60.0 / S["bpm"]
        self.sections = sorted(S["sections"], key=lambda s: s["startBeat"])
        self.chords = sorted(S["chords"], key=lambda c: c["startBeat"])
        self.cuts = [(a, a + b) for a, b, _ in S["parts"]["bass"]["cuts"] if a < 296]   # outro bar 3 is arranged below
        self.sil = [(a * self.spb, (a + b) * self.spb) for a, b, _ in S["parts"]["silence"]]

    def section(self, beat):
        cur = self.sections[0]["name"]
        for s in self.sections:
            if beat >= s["startBeat"] - 1e-9:
                cur = s["name"]
        return cur

    def cut(self, notes):
        """drop / shorten notes (beats) that sound inside a cut window"""
        out = []
        for m, b, d, v in notes:
            e = b + d
            for a, z in self.cuts:
                if a <= b < z:
                    d = 0
                    break
                if b < a < e:
                    e = a
                    d = e - b
            if d > 0.05:
                out.append((m, b, d, v))
        return out

    def sec_notes(self, notes):
        return [(m, b * self.spb, d * self.spb, v) for m, b, d, v in notes]

    # ---- keys
    def keys(self):
        ep, piano, strings, pad = [], [], [], []
        for c in self.chords:
            b0, L, sym = c["startBeat"], c["beats"], c["symbol"]
            sec = self.section(b0)
            v = c["notes"][1:]
            if sec == "boot" or b0 >= 300:                          # the boot chord and the end chord
                ep += [(m, b0, L - 0.05, 52) for m in v]
                strings += [(m, b0, L - 0.05, 70) for m in v]
                pad += [(m, b0, L - 0.05, 58) for m in v[:4]]
            elif sec in ("intro", "verse1", "verse2", "post1", "post2") or (sec == "outro" and b0 < 296):
                pat = [(0, 1.4, 60), (1.5, 0.45, 48), (2.5, 1.4, 54)] if L >= 4 else [(0, 1.4, 60), (1.5, 0.45, 48)]
                ep += [(m, b0 + o, d, vel) for o, d, vel in pat for m in v]
            elif sec in ("pre1", "pre2"):
                ep += [(m, b0, L - 0.05, 54) for m in v]
                strings += [(m, b0, L - 0.02, 76) for m in v]
            elif sec in ("chorus1", "chorus2", "chorus3"):
                ep += [(m, b0, L - 0.05, 46) for m in v]
                for k in range(int(L)):
                    piano += [(m + 12, b0 + k + 0.5, 0.32, 64 if k % 2 == 0 else 56) for m in v]
                strings += [(m, b0, L - 0.02, 72) for m in v]
                pad += [(m, b0, L - 0.02, 50) for m in v[:4]]
            elif sec == "bridge":
                if b0 >= 232:
                    ep += [(m, b0, L - 0.05, 54) for m in v]
                    pad += [(m, b0, L - 0.02, 56) for m in v]
                    strings += [(m, b0, L - 0.02, 64) for m in v]
            elif sec == "breakdown":
                if 244 <= b0 < 252:
                    piano += [(m, b0, L - 0.1, 46) for m in v]
                elif b0 >= 252:
                    strings += [(m, b0, L - 0.02, 66) for m in v]
                    pad += [(m, b0, L - 0.02, 54) for m in v]
            elif sec == "outro" and 296 <= b0 < 300:
                piano += [(m, b0, L - 0.05, 56) for m in v]
                ep += [(m, b0, L - 0.05, 40) for m in v]
        # the bridge comp: EP stabs on the big-beat kick rhythm (keys.bridgeComp)
        for st in self.S["parts"]["keys"].get("bridgeComp", []):
            ep += [(m, st["startBeat"], 0.4, 70) for m in st["notes"]]
        # the stabs (the HAND hits, the chorus hits, the era changes): piano + EP, not brass
        for st in self.S["parts"]["stabs"]["brass"]:
            piano += [(m, st["startBeat"], 0.45, 90) for m in st["notes"]] + [(m + 12, st["startBeat"], 0.45, 80) for m in st["notes"]]
        # pre-chorus strings swell (CC11 across the section, as the old riser did)
        cc = []
        for s in self.sections:
            if s["name"] in ("pre1", "pre2"):
                a, z = s["startBeat"], s["startBeat"] + 13.5
                for k in range(28):
                    cc.append((a + (z - a) * k / 27, 11, int(45 + 75 * k / 27)))
                cc.append((s["startBeat"] + s["beats"], 11, 100))
            elif s["name"] in ("boot",):
                for k in range(9):
                    cc.append((k * 0.5, 11, int(60 + 50 * k / 8)))
                cc.append((8, 11, 100))
        cc.sort()
        T = self.dur
        parts = {
            "ep": gm(self.sec_notes(self.cut(ep)), EP, T, tag="ep"),
            "piano": gm(self.sec_notes(self.cut(piano)), PIANO, T, tag="piano"),
            "strings": gm(self.sec_notes(self.cut(strings)), STRINGS, T, cc=[(b * self.spb, c, v) for b, c, v in cc], tag="strings"),
            "pad": gm(self.sec_notes(self.cut(pad)), PAD, T, tag="pad"),
        }
        return parts

    # ---- bass: the two floppy drives' notes, on a warm fingered bass
    def bass(self):
        notes = []
        for name, vel in (("floppyA", 96), ("floppyB", 72)):
            for t, m, d in self.E[name]:
                m = int(m)
                while m < 31:
                    m += 12
                while m > 55:
                    m -= 12
                notes.append((m, t, max(0.09, d * 0.9), vel))
        notes = self._sil_cut(notes)
        return gm(notes, BASS, self.dur, tag="bass", cal_note=40)

    def _sil_cut(self, notes):
        out = []
        for m, t, d, v in notes:
            for a, z in self.sil:
                if a <= t < z:
                    d = 0
                elif t < a < t + d:
                    d = a - t
            if d > 0.02:
                out.append((m, t, d, v))
        return out

    # ---- melodic accents: glockenspiel bells, the bridge years on celesta, the riff on a soft organ
    def mallets(self):
        bells = [(int(m), t, 0.6, 92) for t, m in self.E["bell"]]
        beeps = [(int(m), t, 0.45, 74) for t, m in self.E["beep"]]
        riff = [(int(m), t, max(0.08, d * 0.92), 70) for t, m, d in self.E["riff"]]
        return {"glock": gm(bells, GLOCK, self.dur, tag="glock", cal_note=84),
                "celesta": gm(beeps, CELESTA, self.dur, tag="celesta", cal_note=72),
                "organ": gm(self._sil_cut(riff), ORGAN, self.dur, tag="organ", cal_note=67)}

    # ---- drums: a natural GM kit on the EVENTS times
    def drums(self):
        E, T = self.E, self.dur
        beat = lambda t: t / self.spb

        def vel_kick(t):
            b = beat(t)
            return 112 if abs(b / 4 - round(b / 4)) < 1e-6 else (104 if abs(b - round(b)) < 1e-6 else 92)

        def vel_hat(t):
            b = beat(t)
            f = b - math.floor(b + 1e-9)
            base = 70 if f < 1e-6 else (58 if abs(f - 0.5) < 1e-6 else 46)
            return base + (int(round(b * 4)) * 7919 % 9) - 4

        builds = [(28.0, 34.75), (76.0, 82.75)]

        def vel_snare(t):
            for a, z in builds:
                if a <= t < z and (t - a) > 4.0:
                    return int(64 + 44 * (t - a) / (z - a))
            return 100

        tracks = {}
        spec = {
            "kick": [(DRUM["kick"], t, 0.2, vel_kick(t)) for t in E["kick"]],
            "snare": [(DRUM["snare"], t, 0.2, vel_snare(t)) for t in E["snare"]] +
                     [(DRUM["ghost"], t, 0.1, 34) for t in E["ghost"]],
            "clap": [(DRUM["clap"], t, 0.2, 88) for t in E["clap"]] + [(DRUM["snap"], t, 0.1, 64) for t in E["snap"]],
            "hats": [(DRUM["hat"], t, 0.1, vel_hat(t)) for t in E["hat"] if t not in set(E["openHat"])] +
                    [(DRUM["openHat"], t, 0.25, 66) for t in E["openHat"]],
            "cymbals": [(DRUM["crash"], t, 1.0, 96) for t in E["crash"]] + [(DRUM["chokedCrash"], t, 0.3, 88) for t in E["chokedCrash"]],
            "perc": [(DRUM["tambourine"], t, 0.1, 40 + (8 if abs(beat(t) * 2 - round(beat(t) * 2)) < 1e-6 else 0)) for t in E["tambourine"]] +
                    [(DRUM["tom"], t, 0.3, 84) for t in E["tom"]],
            "keystroke": [(DRUM["keystroke"], t, 0.1, 46) for t in E["keystroke"][:1]],
        }
        for name, notes in spec.items():
            cal = notes[0][0] if notes else 38
            tracks[name] = gm(notes, 0, T, channel=9, tag="dr_" + name, cal_note=cal)
        return tracks


