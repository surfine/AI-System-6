#!/usr/bin/env python3
"""build_guide.py: renders build/guide.wav, the source that ACE-Step 1.5 covers.

    python3 -I music/build_guide.py              # render + measure (Whisper, pitch, loudness; ~6 min)
    python3 -I music/build_guide.py --no-qa      # render only (~2 min with warm caches)
    python3 -I music/build_guide.py --workers 4

The final song is regenerated by ACE-Step 1.5 in cover mode (music/ace_cover.py), which keeps the
source's structure and tempo and re-sings it with a realistic voice.  This is that source: the new
Kokoro singer (music/sing_world.py, af_heart) clear and in tune on top of a warm, simple band that
follows the score's chords and sections and plays its drums on the exact EVENTS times of data/data.js.
Nothing here changes a timing: every note comes from score.json, every drum hit from data.js.

Writes (48 kHz, 24-bit, stereo, exactly DUR long):
  build/guide.wav               the mix: -14 LUFS integrated, true peak <= -1 dBTP
  build/guide_vocals.wav        the vocal bus (with its reverb) through the master's gain
  build/guide_instrumental.wav  the band through the same gain (vocals + instrumental = guide)
  build/guide_stems/*.wav       pre-master tracks: lead chant choir spoken chops drums bass keys strings mallets
  build/guide-qa.json           the measurements (music/guide_qa.py)
The old engine (build_song.py -> build/song.wav) is untouched.  See music/PRODUCTION.md, "Guide for
ACE-Step cover".
"""
