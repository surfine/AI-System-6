# FluidSynth (any channel), cached, latency-compensated
# ------------------------------------------------------------------------------------------------
def _fluid_render(notes_beats, program, channel, wav, cc=None, gain=0.5):
    mid = wav[:-4] + ".mid"
    write_midi(mid, notes_beats, program, channel=channel, cc=cc)
    subprocess.run(["fluidsynth", "-ni", "-q", "-R", "0", "-C", "0", "-g", str(gain), "-r", str(SR),
                    "-o", "synth.polyphony=256", "-T", "wav", "-O", "float", "-F", wav, SF2, mid],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    os.remove(mid)


def latency(program, channel, note):
    """Onset latency (s) of a GM program / drum note: one calibration note, measured at 10 % of peak."""
    os.makedirs(FLUID, exist_ok=True)
    wav = os.path.join(FLUID, "gcal_%d_%d_%d.wav" % (program, channel, note))
    if not os.path.exists(wav):
        _fluid_render([(note, 1.0, 1.0, 100)], program, channel, wav)
    y, _ = sf.read(wav, dtype="float64", always_2d=True)
    m = np.abs(y).max(axis=1)
    i0 = int(0.5 * SR)
    seg = m[i0 - 200:i0 + 6000]
    k = int(np.argmax(seg > 0.1 * seg.max()))
    return max(0.0, (k - 200) / SR)


def gm(notes, program, total_s, channel=0, cc=None, tag="gm", cal_note=60):
    """notes: [(midi, start s, dur s, velocity)]; cc: [(t s, controller, value)] -> stereo, total_s long."""
    nb = [(int(m), round(t * 2, 6), round(max(d, 0.02) * 2, 6), int(v)) for m, t, d, v in notes]
    cb = [(round(t * 2, 6), int(c), int(v)) for t, c, v in (cc or [])]
    key = hashlib.sha1(json.dumps([nb, program, channel, cb, round(total_s, 3), "g2"]).encode()).hexdigest()[:20]
    os.makedirs(FLUID, exist_ok=True)
    wav = os.path.join(FLUID, "guide_%s_%s.wav" % (tag, key))
    if not os.path.exists(wav):
        _fluid_render(nb, program, channel, wav, cb)
    y, sr = sf.read(wav, dtype="float64", always_2d=True)
    assert sr == SR
    sh = int(round(max(0.0, latency(program, channel, cal_note) - 0.0008) * SR))
    y = y[sh:]
    out = np.zeros((n_of(total_s), 2))
    k = min(len(out), len(y))
    out[:k] = y[:k]
    return out


